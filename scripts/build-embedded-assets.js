/**
 * @file scripts/build-embedded-assets.js
 * Generates an in-memory embedded asset registry from src/public for standalone single-executable builds.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const publicDir = path.resolve(__dirname, '../src/public');
const outputFile = path.resolve(__dirname, '../src/server/embedded-assets.js');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon'
};

function collectFiles(dir, baseDir = dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectFiles(fullPath, baseDir));
    } else if (entry.isFile()) {
      const relativePath = '/' + path.relative(baseDir, fullPath).replace(/\\/g, '/');
      const ext = path.extname(entry.name).toLowerCase();
      const mimeType = MIME_TYPES[ext] || 'application/octet-stream';
      const isBinary = ['.png', '.ico', '.jpg', '.jpeg'].includes(ext);
      const content = isBinary ? fs.readFileSync(fullPath).toString('base64') : fs.readFileSync(fullPath, 'utf8');
      files.push({ path: relativePath, mimeType, content, isBinary });
    }
  }

  return files;
}

const socketClientPath = path.resolve(__dirname, '../node_modules/socket.io/client-dist/socket.io.js');

const files = collectFiles(publicDir);
const assetMap = {};

// Socket.IO normally reads its browser client from node_modules at runtime, which does not exist inside the
// standalone executable, so the client script is embedded and served by server.js instead.
if (!fs.existsSync(socketClientPath)) {
  throw new Error(`Socket.IO browser client not found at ${socketClientPath}. Run "npm install" first.`);
}
// The virtual camera driver installer (lan-camera-setupv<version>.exe, built by vcam/build.bat before this step in
// build.bat) is embedded too, so the standalone exe can serve /download/lan-camera-setup from any folder.
const distDir = path.resolve(__dirname, '../dist');
const installerNames = fs.existsSync(distDir)
  ? fs.readdirSync(distDir).filter((name) => /^lan-camera-setupv.+\.exe$/i.test(name))
  : [];
if (installerNames.length > 0) {
  installerNames.sort((a, b) => fs.statSync(path.join(distDir, b)).mtimeMs - fs.statSync(path.join(distDir, a)).mtimeMs);
  const installerName = installerNames[0];
  files.push({
    path: '/download/lan-camera-setup.exe',
    mimeType: 'application/octet-stream',
    content: fs.readFileSync(path.join(distDir, installerName)).toString('base64'),
    isBinary: true,
    fileName: installerName
  });
}
files.push({
  path: '/vendor/socket.io.js',
  mimeType: 'application/javascript; charset=utf-8',
  content: fs.readFileSync(socketClientPath, 'utf8'),
  isBinary: false
});

for (const file of files) {
  assetMap[file.path] = {
    content: file.content,
    mimeType: file.mimeType,
    isBinary: file.isBinary,
    ...(file.fileName ? { fileName: file.fileName } : {})
  };
}

const generatedCode = `/**
 * Auto-generated by scripts/build-embedded-assets.js
 * Embedded static assets for standalone single-executable distribution.
 */

export const embeddedAssets = ${JSON.stringify(assetMap, null, 2)};
`;

fs.writeFileSync(outputFile, generatedCode, 'utf8');
console.log(`Successfully generated embedded assets: ${files.length} files -> ${outputFile}`);
